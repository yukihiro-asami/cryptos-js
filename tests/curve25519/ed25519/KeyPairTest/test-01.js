import { keyPair } from '../../../../src/curve25519/ed25519/key-pair.js';
import { equal } from 'assert';


// Test vector from RFC 8032, Section 7.1
const seed = Uint8Array.from([
    0x9d, 0x61, 0xb1, 0x9d, 0xef, 0xfd, 0x5a, 0x60,
    0xba, 0x84, 0x4a, 0xf4, 0x92, 0xec, 0x2c, 0xc4,
    0x44, 0x49, 0xc5, 0x69, 0x7b, 0x32, 0x69, 0x19,
    0x70, 0x3b, 0xac, 0x03, 0x1c, 0xae, 0x7f, 0x60
]);

const expectedPk = Uint8Array.from([
    0xd7, 0x5a, 0x98, 0x01, 0x82, 0xb1, 0x0a, 0xb7,
    0xd5, 0x4b, 0xfe, 0xd3, 0xc9, 0x64, 0x07, 0x3a,
    0x0e, 0xe1, 0x72, 0xf3, 0xda, 0xa6, 0x23, 0x25,
    0xaf, 0x02, 0x1a, 0x68, 0xf7, 0x07, 0x51, 0x1a
]);

const pk = new Uint8Array(32);
const sk = new Uint8Array(64);

keyPair(pk, sk, seed);

// Check public key
for (let i = 0; i < 32; i++) {
    equal(pk[i], expectedPk[i]);
}

// Check secret key = seed || pk
for (let i = 0; i < 32; i++) {
    equal(sk[i], seed[i]);      // 前半: seed
    equal(sk[i + 32], pk[i]);   // 後半: pk
}

console.log('tests_passed.');