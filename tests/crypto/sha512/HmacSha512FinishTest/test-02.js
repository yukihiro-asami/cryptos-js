import { hmacSha512Init } from '../../../../src/crypto/sha512/hmac-sha512-init.js';
import { hmacSha512Update } from '../../../../src/crypto/sha512/hmac-sha512-update.js';
import { hmacSha512Finish } from '../../../../src/crypto/sha512/hmac-sha512-finish.js';
import { hmacSha512State } from '../../../../src/crypto/sha512/hmac-sha512-state.js';

// === RFC 4231 Test Case 1 ===
const key = Uint8Array.from([
    0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b,
    0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b,
    0x0b, 0x0b, 0x0b, 0x0b
]);
const data = Uint8Array.from([
    0x48, 0x69, 0x20, 0x54, 0x68, 0x65, 0x72, 0x65 // "Hi There"
]);
const expected = Uint8Array.from([
    0x87, 0xaa, 0x7c, 0xde, 0xa5, 0xef, 0x61, 0x9d,
    0x4f, 0xf0, 0xb4, 0x24, 0x1a, 0x1d, 0x6c, 0xb0,
    0x23, 0x79, 0xf4, 0xe2, 0xce, 0x4e, 0xc2, 0x78,
    0x7a, 0xd0, 0xb3, 0x05, 0x45, 0xe1, 0x7c, 0xde,
    0xda, 0xa8, 0x33, 0xb7, 0xd6, 0xb8, 0xa7, 0x02,
    0x03, 0x8b, 0x27, 0x4e, 0xae, 0xa3, 0xf4, 0xe4,
    0xbe, 0x9d, 0x91, 0x4e, 0xeb, 0x61, 0xf1, 0x70,
    0x2e, 0x69, 0x6c, 0x20, 0x3a, 0x12, 0x68, 0x54
]);

const state = hmacSha512State();
hmacSha512Init(state, key);
hmacSha512Update(state, data);

const out = new Uint8Array(64);
hmacSha512Finish(state, out);

// === 署名一致確認 ===
const matched = expected.every((v, i) => v === out[i]);
console.assert(matched, 'FAILED: HMAC-SHA-512 output does not match expected');

console.log('tests_passed.');
